/*
 * Managix i18n — lightweight dictionary-based translation layer.
 *
 * - Language is a per-device preference (localStorage), not a DB setting:
 *   one outlet can run Bangla at the counter while the office runs English.
 * - `t(key)` falls back English → key, and supports {var} interpolation.
 * - Arabic flips the document to RTL via `dir` on <html> (see App.tsx).
 */

export type Lang = "en" | "bn" | "hi" | "ar";

/** BCP-47 locale per language — drives all number/date formatting. */
export const LOCALES: Record<Lang, string> = {
  en: "en-US",
  bn: "bn-BD",
  hi: "hi-IN",
  ar: "ar-EG",
};

/**
 * Active UI language. Kept outside React so pure helpers (fmtMoney, fmtDate…)
 * and lib code (charts, insights) can format in the user's language without
 * threading the language through every call site.
 */
let ACTIVE_LANG: Lang = "en";

export function setActiveLang(lang: Lang): void {
  ACTIVE_LANG = lang;
}

export function activeLang(): Lang {
  return ACTIVE_LANG;
}

export function activeLocale(): string {
  return LOCALES[ACTIVE_LANG];
}

/**
 * Convert ASCII digits in a string to the active language's native digits.
 * (bn → ০১২, hi → ०१२, ar → ٠١٢; en → unchanged.)
 */
export function localizeDigits(s: string): string {
  if (ACTIVE_LANG === "en") return s;
  const maps: Record<Exclude<Lang, "en">, string[]> = {
    bn: ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"],
    hi: ["०", "१", "२", "३", "४", "५", "६", "७", "८", "९"],
    ar: ["٠", "١", "٢", "٣", "٤", "٥", "٦", "٧", "٨", "٩"],
  };
  const map = maps[ACTIVE_LANG];
  return s.replace(/[0-9]/g, (d) => map[Number(d)]);
}

export interface LanguageInfo {
  code: Lang;
  /** Native script name, shown first in the switcher */
  native: string;
  /** English name, shown as subtitle */
  english: string;
  flag: string;
  dir: "ltr" | "rtl";
}

export const LANGUAGES: LanguageInfo[] = [
  { code: "en", native: "English", english: "English", flag: "🇬🇧", dir: "ltr" },
  { code: "bn", native: "বাংলা", english: "Bangla", flag: "🇧🇩", dir: "ltr" },
  { code: "hi", native: "हिन्दी", english: "Hindi", flag: "🇮🇳", dir: "ltr" },
  { code: "ar", native: "العربية", english: "Arabic", flag: "🇸🇦", dir: "rtl" },
];

const LS_KEY = "managix_lang";

export function getStoredLang(): Lang {
  const v = localStorage.getItem(LS_KEY);
  return LANGUAGES.some((l) => l.code === v) ? (v as Lang) : "en";
}

export function storeLang(lang: Lang): void {
  localStorage.setItem(LS_KEY, lang);
}

export function langInfo(lang: Lang): LanguageInfo {
  return LANGUAGES.find((l) => l.code === lang) ?? LANGUAGES[0];
}

